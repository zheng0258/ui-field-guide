import { z } from 'zod'

const HEX_COLOR = /^#[0-9a-f]{6}(?:[0-9a-f]{2})?$/

export const MeasurementSchema = z.object({
  generator: z.string(),
  macOS: z.string(),
  controls: z.record(
    z.string(),
    z.record(z.string(), z.object({ width: z.number().nonnegative(), height: z.number().positive() })),
  ),
  colors: z.record(z.string(), z.object({ light: z.string().regex(HEX_COLOR), dark: z.string().regex(HEX_COLOR) })),
})
export type Measurement = z.infer<typeof MeasurementSchema>

const PREFIX = '--macos'

function controlLines(measurement: Measurement): string[] {
  return Object.entries(measurement.controls)
    .sort(([a], [b]) => a.localeCompare(b))
    .flatMap(([control, sizes]) =>
      Object.entries(sizes)
        .sort(([a], [b]) => a.localeCompare(b))
        .flatMap(([size, metric]) => [
          `${PREFIX}-${control}-${size}-height: ${metric.height}px;`,
          // A width of 0 means the control stretches; only fixed-width controls get a width token.
          ...(metric.width > 0 ? [`${PREFIX}-${control}-${size}-width: ${metric.width}px;`] : []),
        ]),
    )
}

function colorLines(measurement: Measurement, scheme: 'light' | 'dark'): string[] {
  return Object.entries(measurement.colors)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, value]) => `${PREFIX}-color-${name}: ${value[scheme]};`)
}

const indent = (lines: readonly string[], depth: number) => lines.map((line) => `${'  '.repeat(depth)}${line}`)

/** Renders the measurement as CSS custom properties: light by default, dark via OS setting or data-theme. */
export function renderTokens(measurement: Measurement, sourcePath: string): string {
  const dark = colorLines(measurement, 'dark')
  return [
    '/*',
    ` * GENERATED by scripts/build-tokens.ts from ${sourcePath}`,
    ` * (${measurement.generator}, measured on macOS ${measurement.macOS}). Do not edit by hand.`,
    ' * Re-generate: pnpm tokens:measure && pnpm tokens:build',
    ' */',
    ':root {',
    ...indent(['color-scheme: light dark;', ...controlLines(measurement), ...colorLines(measurement, 'light')], 1),
    '}',
    '',
    '@media (prefers-color-scheme: dark) {',
    "  :root:not([data-theme='light']) {",
    ...indent(dark, 2),
    '  }',
    '}',
    '',
    ":root[data-theme='dark'] {",
    ...indent(dark, 1),
    '}',
    '',
  ].join('\n')
}
