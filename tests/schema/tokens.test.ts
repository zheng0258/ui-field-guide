import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'
import { MeasurementSchema, renderTokens, type Measurement } from '../../scripts/tokens'

const root = join(import.meta.dirname, '..', '..')

const sample: Measurement = {
  generator: 'tools/measure-macos',
  macOS: '26.0.0',
  controls: { slider: { regular: { width: 0, height: 16 } }, 'push-button': { small: { width: 55, height: 20 } } },
  colors: { label: { light: '#000000d8', dark: '#ffffffd8' } },
}

describe('renderTokens', () => {
  const css = renderTokens(sample, 'macos.json')

  it('marks the file as generated with its source', () => {
    expect(css.startsWith('/*\n * GENERATED by scripts/build-tokens.ts from macos.json')).toBe(true)
  })

  it('emits width only for fixed-width controls', () => {
    expect(css).toContain('--macos-push-button-small-width: 55px;')
    expect(css).toContain('--macos-slider-regular-height: 16px;')
    expect(css).not.toContain('--macos-slider-regular-width')
  })

  it('emits light colors by default and dark colors for both dark switches', () => {
    expect(css).toContain('--macos-color-label: #000000d8;')
    expect(css.match(/--macos-color-label: #ffffffd8;/g)).toHaveLength(2)
    expect(css).toContain('@media (prefers-color-scheme: dark)')
    expect(css).toContain(":root[data-theme='dark']")
  })
})

describe('committed tokens', () => {
  it('match the committed measurement exactly', () => {
    const source = 'tools/measure-macos/output/macos.json'
    const measurement = MeasurementSchema.parse(JSON.parse(readFileSync(join(root, source), 'utf8')))
    expect(readFileSync(join(root, 'src/tokens/macos.css'), 'utf8')).toBe(renderTokens(measurement, source))
  })

  it('include about 35 system colors', () => {
    const measurement = MeasurementSchema.parse(
      JSON.parse(readFileSync(join(root, 'tools/measure-macos/output/macos.json'), 'utf8')),
    )
    expect(Object.keys(measurement.colors).length).toBeGreaterThanOrEqual(35)
  })
})
